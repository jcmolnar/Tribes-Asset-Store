function getRepairMaster(%minToPlace)
{
	%leader = "";
	%leadericnt = 0;
	%leaderpcnt = 0;
	%leadertotal = 0;
	%numclients = getNumClients();
	for(%i = 0;%i < %numclients;%i++)
	{
		%clientList[%i] = getClientByIndex(%i);
		%player = Client::getOwnedObject(%clientlist[%i]);
		if(%player == -1)
			continue;
		%icnt = Player::getItemCount(%player,repitempoints);
		%pcnt = Player::getItemCount(%player,repmatepoints); // PORT: was repitempoints twice
		%total = %icnt + %pcnt;
		if(%total > %leadertotal) // PORT: was %leadercnt, never set
		{
			%leader = %clientlist[%i];	
			%leadericnt = %icnt;
			%leaderpcnt = %pcnt;
			%leadertotal = %total;
		}
	}
	if(%leadertotal < %minToPlace)
		return "";
	else
		return %leader;
}

