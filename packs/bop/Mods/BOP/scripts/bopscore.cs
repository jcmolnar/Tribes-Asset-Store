function getMaster(%type,%minToPlace)
{	
	%leader = "";
	%leadercnt = 0;
	%numclients = getNumClients();
	for(%i = 0;%i < %numclients;%i++)
	{
		%clientList[%i] = getClientByIndex(%i);
		%player = Client::getOwnedObject(%clientList[%i]);
		if(%player == -1)
			continue;
		%cnt = Player::getItemCount(%player,%type);
		if(%cnt > %leadercnt)
		{
			%leader = %clientlist[%i];
			%leadercnt = %cnt;
		}
	}
	if(%leadercnt < %minToPlace)
		return "";
	else
		return %leader;
}

