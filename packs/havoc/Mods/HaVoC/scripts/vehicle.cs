function Tomahawk::onFire(%this) {
	if(!Vehicle::fireWeapon(%this, 3.5)) return;
	playsound(SoundFireFlierRocket, GameBase::getPosition(%this));
	%trans = GameBase::getMuzzleTransform(%this); 
	%vel = Item::getVelocity(%this); 
	if(GameBase::getLOSInfo(%this, 500)) { 
		%object = $los::object;
		if(getObjectType(%object) == "Flier") { 
			%targetId = GameBase::getControlClient(%object); 
			%targetName = Client::getName(%targetId); 
			%client = GameBase::getControlClient(%this); 
			%name = Client::getName(%client);
			if(%targetName == "") {
				Client::sendMessage(%client, 0, "Lock Aquired: " @ GameBase::getDataName(%object).description @ "~wmine_act.wav");
			} else {
				Client::sendMessage(%client, 0, "Lock Aquired: " @ GameBase::getDataName(%object).description @ " piloted by " @ %targetName @ "~wmine_act.wav");
				Client::sendMessage(%targetId, 0, "WARNING - " @ %name @ " has a Tomahawk Missile lock!~waccess_denied.wav"); 
				schedule("Client::sendMessage(" @ %targetId @ ",0,\"~waccess_denied.wav\");", 0.5); 
				schedule("Client::sendMessage(" @ %targetId @ ",0,\"~waccess_denied.wav\");", 1.0);
			}
			Projectile::spawnProjectile("TomahawkLockingMissile", %trans, %this, %vel, %object); 
		} else
			Projectile::spawnProjectile("TomahawkMissile",%trans,%this,%vel);
	} else
		Projectile::spawnProjectile("TomahawkMissile",%trans,%this,%vel); 
	Projectile::spawnProjectile("RMiniFlierRocket",%trans,%this,%vel); 
	Projectile::spawnProjectile("RMiniFlierRocket",%trans,%this,%vel); 
	Projectile::spawnProjectile("RMiniFlierRocket",%trans,%this,%vel); 
