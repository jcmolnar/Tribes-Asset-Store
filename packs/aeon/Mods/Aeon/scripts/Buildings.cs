function CnToolImage::onFire(%player,%slot)
{
	%clientId = Player::getClient(%player);
	if(Player::getMountedItem(%player,$WeaponSlot) != "CnTool" || getSimTime() < %clientId.nextCnTool)
		return;
	%ID = Aeon::getAeonID(%clientId);
	%mod = $Aeon::ClientInfo[%ID,cMod];
	if(%mod < 0 || %mod == "")
		%mod = $Aeon::ClientInfo[%id,cMod] = 1;
	if(%mod == 7) {
		if((%obj = %clientId.lastPiece)) {
			if(%clientId.lastCMod > 0 && %clientId.lastCMod < 7) {
				GameBase::setPosition(%obj,%obj.lastPos);
				GameBase::setRotation(%obj,%obj.lastRot);
				bottomPrint(%clientId,"<jc><f2>Last moved piece reset.",5);
				%prop = Property::getPieceOwn(%obj);
				Aeon::ExportProperty(%prop);
			}
			else
				bottomPrint2(%clientId,"<jc><f2>You currently cannot undo.",5,"C_BuySell.wav");
			%clientId.lastPiece = "";
			Player::trigger(%player,$WeaponSlot,false);
		}
		else {
			bottomPrint2(%clientId,"<jc><f2>You currently cannot undo.",5,"C_BuySell.wav");
			Player::trigger(%player,$WeaponSlot,false);
		}
		return;
	}
	if($CnHold[%player] == "true" && $CnGrab[%player] != "") {
		%obj = $CnGrab[%player];
		if(nullPos(%obj)) {
			Player::trigger(%player,$WeaponSlot,false);
			CnTool::isHolding(%player);
			return;
		}
		%gDs = %obj.cnGrabDst;
		%gRt = %obj.cdGrabRot;
		%oPs = GameBase::getPosition(%obj);
		%oRt = GameBase::getRotation(%obj);
		%pos = GameBase::getPosition(%player);
		%pos = Vector::add(%pos,"0 0 1.8");
		%rot = Player::getLookRot(%player,1);
		%data = GameBase::getDataName(%obj);
		%tempAngle = %clientId.archAngle;
		if(!%tempAngle || %tempAngle < 1)
			%tempAngle = %clientId.archAngle = 2;
		if(%clientId.archConst == "")
			%clientId.archConst = "true true true";
		%constX = getWord(%clientId.archConst,0);
		%constY = getWord(%clientId.archConst,1);
		%constZ = getWord(%clientId.archConst,2);
		if(%obj.moveOnly) {
			%pVec = Vector::getFromRot(%rot,%gDs);
			%aPos = Vector::add(%pos,%pVec);
			if(getObjectType(%obj) == "Item" || getObjectType(%obj) == "Player") {
				if((getObjectType(%obj) == "Player" && !Aeon::inProperty(GameBase::getPosition(%obj))) && !%clientId.isSuperAdmin) {
					Player::trigger(%player,$WeaponSlot,false);
				}
				%nVec = Vector::sub(%aPos,%oPs);
				%strength = $Aeon::ClientInfo[%id,skll,mStr];
				if(%strength == "")
					%strength = $Aeon::ClientInfo[%id,skll,mStr] = 1;
				if(%player.moveOnly) {
					%grabber = %player.cnGrabber;
					%gClient = Player::getClient(%grabber);
					%gStrong = $Aeon::ClientInfo[Aeon::getAeonID(%gClient),skll,mStr];
					%dif = %strength-%gStrong;
					%dst = Vector::getDistance(%pos,%oPs);
					if(%dif < 0 || %dst > 20)
						Player::trigger(%player,$WeaponSlot,false);
				}
				%nVec = Vector::mult(%nVec,%strength@" "@%strength@" "@%strength);
				Item::setVelocity(%obj,%nVec);
			}
			else
				GameBase::setPosition(%obj,%aPos);
		}
		else if(%data.className == "Harvest") {
			%pVec = Vector::getFromRot(%rot,%gDs);
			if(%obj.stickTo && (getWord(%obj.stickTo,3) > getWord(Vector::add(%pos,%pVec),2) || getWord(%obj.stickTo,3) - getWord(Vector::add(%pos,%pVec),2) > 0.5))
				%pVec = Vector::splice(%pVec,%pVec,"0 0 0");
			%newPos = Vector::add(%pos,%pVec);
			if(getLOSinfo(Vector::add(%newPos,"0 0 2"),Vector::sub(%newPos,"0 0 1000"),1) && $los::object != %obj) {
				if(getWord(%newPos,2) < getWord($los::position,2))
					%newPos = Vector::splice(%newPos,%newPos,$los::position);
				%dstChk = Vector::getDistance(%newPos,$los::position);
				if(%dstChk < 0.1) {
					%newPos = $los::position;
					%obj.stickTo = $los::object@" "@%newPos;
				}
				else if(%dstChk > 3)
					%obj.stickTo = "";
			}
			%obj.vel = Vector::sub(%newPos,%oPs);
			GameBase::setPosition(%obj,%newPos);
			%clientId.nextCnTool = getSimTime()+0.1;
		}
		else if(%obj.isCoconut) {
			%obj = Coconut::shapeSwap(%obj);
			$CnGrab[%player] = %obj;
			%obj.cnGrabDst = %gDs;
			%obj.cnGrabber = %player;
			%pVec = Vector::getFromRot(%rot,%gDs);
			%aPos = Vector::add(%pos,%pVec);
			%aPos = Vector::add(%aPos,"0 0 0");
			%nVec = Vector::sub(%aPos,%oPs);
			%strength = $Aeon::ClientInfo[%id,skll,mStr];
			if(%strength == "")
				%strength = $Aeon::ClientInfo[%id,skll,mStr] = 1;
			%nVec = Vector::mult(%nVec,%strength@" "@%strength@" "@%strength);
			GameBase::setRotation(%obj,Vector::getRotation(%nVec));
			Item::setVelocity(%obj,%nVec);
		}
		else if(%obj.isRock) {
			%fresh = ($Aeon::rockStay*60)-(getSimTime()-%obj.isRock);
			%pVec = Vector::getFromRot(%rot,%gDs);
			%newPos = Vector::add(%pos,%pVec);
			if(Vector::speed(%player) < 0.5)
				%obj.deleting++;
			%progress = floor((33-%obj.deleting)*3);
			if(%progress == 0) {
				Aeon::rockToCash(%clientId,%obj);
				Player::trigger(%player,$WeaponSlot,false);
				%clientId.tempGot = true;
			}
			else {
				bottomPrint(%clientId,"<jc><f1>Construction Operations:<f2> converting mineral %"@%progress,5);
				GameBase::setRotation(%obj,Vector::add(%oRt,"0 "@$Pi/10@" 0"));
				GameBase::setPosition(%obj,%newPos);
			}
			%clientId.nextCnTool = getSimTime()+0.1;
		}
		else if(%mod == 1) {
			if(Aeon::inProperty(Vector::add(%pos,Vector::getFromRot(%rot,%gDs))) != true) {
				Player::trigger(%player,$WeaponSlot,false);
				%gDs--;
			}
			%pVec = Vector::getFromRot(%rot,%gDs);
			%newPos = Vector::add(%pos,%pVec);
			%newPos = Vector::sub(%newPos,%obj.offVec);
			if(%constX == false)
				%newPos = Vector::splice(%oPs,%newPos,%newPos);
			if(%constY == false)
				%newPos = Vector::splice(%newPos,%oPs,%newPos);
			if(%constZ == false)
				%newPos = Vector::splice(%newPos,%newPos,%oPs);
			GameBase::setPosition(%obj,%newPos);
			$lastPos[%obj] = %newPos;
			//%clientId.nextCnTool = getSimTime()+0.0;
		}
		else if(%mod == 2) {
			if(Aeon::inProperty(Vector::add(%pos,Vector::getFromRot(%rot,%gDs))) != true) {
				Player::trigger(%player,$WeaponSlot,false);
				%gDs--;
			}
			%pVec = Vector::getFromRot(%rot,%gDs);
			if(%obj.stickTo && (getWord(%obj.stickTo,3) > getWord(Vector::add(%pos,%pVec),2) || getWord(%obj.stickTo,3) - getWord(Vector::add(%pos,%pVec),2) > 0.5))
				%pVec = Vector::splice(%pVec,%pVec,"0 0 -1.8");
			%newPos = Vector::add(%pos,%pVec);
			if(getLOSinfo(Vector::add(%newPos,"0 0 2"),Vector::sub(%newPos,"0 0 1000"),1) && $los::object != %obj) {
				if(getWord(%newPos,2) < getWord($los::position,2))
					%newPos = Vector::splice(%newPos,%newPos,$los::position);
				%dstChk = Vector::getDistance(%newPos,$los::position);
				if(%dstChk < 0.5) {
					%newPos = $los::position;
					%obj.stickTo = $los::object@" "@%newPos;
				}
				if(%dstChk > 5)
					%obj.stickTo = "";
			}
			%newPos = Vector::sub(%newPos,%obj.offVec);
			if(%constX == false)
				%newPos = Vector::splice(%oPs,%newPos,%newPos);
			if(%constY == false)
				%newPos = Vector::splice(%newPos,%oPs,%newPos);
			if(%constZ == false)
				%newPos = Vector::splice(%newPos,%newPos,%oPs);
			GameBase::setPosition(%obj,%newPos);
			$lastPos[%obj] = %newPos;
			%clientId.nextCnTool = getSimTime()+0.1;
		}
		else if(%mod == 3) {
			%pVec = Vector::getFromRot(%rot,30);
			%newPos = Vector::add(%pos,%pVec);
			if(GameBase::getLOSInfo(%player,20)) {
				%losPos = $los::position;
				%losNrm = $los::normal;
				%losObj = $los::object;
				$los::position = "";
				$los::normal = "";
				$los::object = "";
				if(%losObj != %obj && %losObj != %player && getObjectType(%losObj) != "Player" && getObjectType(%losObj) != "Flier" && getObjectType(%losObj) != "Item") {
					GameBase::setPosition(%obj,%losPos);
					GameBase::setRotation(%obj,Vector::getRotation(%losNrm));
					$lastPos[%obj] = %losPos;
				}
			}
			%clientId.nextCnTool = getSimTime()+0.1;
		}
		else if(%mod == 4) {
			%dif = Vector::sub(%rot,%gRt);
			%newRot = Vector::add(%oRt,%dif);
			%newRot = Vector::round(%newRot,10);
			GameBase::setRotation(%obj,%newRot);
			%obj.cdGrabRot = %newRot;
			//%clientId.nextCnTool = getSimTime()+0.0;
		}
		else if(%mod == 5 && getSimTime() > (%obj.lastRotTm+0.8)) {
			%dif = Vector::sub(%rot,%gRt);
			%xDif = 0;
			%yDif = 0;
			%zDif = 0;
			if(getWord(%dif,0) > 0.3)
				%xDif = $Pi/%tempAngle;
			else if(getWord(%dif,0) < -0.3)
				%xDif = $Pi/-%tempAngle;
			if(getWord(%dif,2) > 0.3)
				%zDif = $Pi/-%tempAngle;
			else if(getWord(%dif,2) < -0.3)
				%zDif = $Pi/%tempAngle;
			%newRot = Vector::add(%oRt,"0 "@%yDif@" "@%zDif);
			%newRot = Vector::add(%newRot,%xDif@" 0 0");
			GameBase::setRotation(%obj,%newRot);
			%obj.lastRotTm = getSimTime();
			%obj.cdGrabRot = %newRot;
			%clientId.nextCnTool = getSimTime()+0.2;
		}
		else if(%mod == 6 && getSimTime() > (%obj.lastRotTm+0.8)) {
			%dif = Vector::sub(%rot,%gRt);
			%xDif = 0;
			%yDif = 0;
			%zDif = 0;
			if(getWord(%dif,0) > 0.3)
				%xDif = $Pi/%tempAngle;
			else if(getWord(%dif,0) < -0.3)
				%xDif = $Pi/-%tempAngle;
			if(getWord(%dif,2) > 0.3)
				%yDif = $Pi/-%tempAngle;
			else if(getWord(%dif,2) < -0.3)
				%yDif = $Pi/%tempAngle;
			%newRot = Vector::add(%oRt,%xDif@" "@%yDif@" "@%zDif);
			GameBase::setRotation(%obj,%newRot);
			%obj.lastRotTm = getSimTime();
			%obj.cdGrabRot = %newRot;
			%clientId.nextCnTool = getSimTime()+0.2;
		}
		else if(%mod == 8) {
			%oNm = GameBase::getMapName(%obj);
			%typ = getObjectType(%obj);
			if(%oNm == "" || %oNm == -1) {
				if(%typ == "InteriorShape")
					%oNm = "A wall";
				else if(%typ == "StaticShape")
					%oNm = "An object";
			}
			if(Vector::speed(%player) < 0.5)
				%obj.deleting++;
			%progress = floor((10-%obj.deleting)/2);
			%msg = "unlocking "@%oNm;
			if(%obj.locked != true)
				%msg = "locking "@%oNm@" in place";
			bottomPrint(%clientId,"<jc><f1>Construction Operations:<f2> "@%msg@", "@%progress,5);
			if(%progress == "0") {
				%clientId.tempGot = true;
				Player::trigger(%player,$WeaponSlot,false);
				if(%obj.locked != true) {
					%obj.locked = true;
					bottomPrint(%clientId,"<jc><f1>"@%oNm@" locked in place.",5);
				}
				else {
					%obj.locked = "";
					bottomPrint(%clientId,"<jc><f1>"@%oNm@" unlocked.",5);
				}
				Aeon::ExportProperty(Property::getPieceOwn(%obj));
			}
		}
		else if(%mod == 9) {
			%oNm = GameBase::getMapName(%obj);
			%typ = getObjectType(%obj);
			if(%oNm == "" || %oNm == -1) {
				if(%typ == "InteriorShape")
					%oNm = "A wall";
				else if(%typ == "StaticShape")
					%oNm = "An object";
			}
			if(Vector::speed(%player) < 0.5)
				%obj.deleting++;
			%progress = floor((10-%obj.deleting)/2);
			bottomPrint(%clientId,"<jc><f1>Construction Operations:<f2> deleting "@%oNm@" "@%progress,5);
			if(%progress == "0") {
				%prop = Property::getPieceOwn(%obj);
				%clientId.tempGot = true;
				Player::trigger(%player,$WeaponSlot,false);
				bottomPrint(%clientId,"<jc><f1>"@%oNm@" deleted.",5);
				Property::delete(%obj);
				Aeon::ExportProperty(%prop);
			}
		}
	}
	else if(GameBase::getLOSInfo(%player,20)) {
		%obj = $los::object;
		%lPs = $los::position;
		$los::object = "";
		$los::position = "";
		if($CnGrab[%player] != "" && $CnGrab[%player] != %obj) {
			Player::trigger(%player,$WeaponSlot,false);
			CnTool::isHolding(%player);
			return;
		}
		if(%obj.cnGrabber) {
			Player::trigger(%player,$WeaponSlot,false);
			return;
		}
		%typ = getObjectType(%obj);
		%data = GameBase::getDataName(%obj);
		if(%typ != "SimTerrain" && %data.className != "FencePost") {
			%pos = GameBase::getPosition(%player);
			%oNm = GameBase::getMapName(%obj);
			if(%oNm == "" || %oNm == -1 || %oNm == false) {
				if(%typ == "InteriorShape")
					%oNm = "A wall";
				else if(%typ == "StaticShape")
					%oNm = "An object";
			}
			if(%obj.locked != true || $CnModName[$Aeon::ClientInfo[%id,cMod]] == "Lock") {
				%rot = GameBase::getRotation(%player);
				%dst = Vector::getDistance(%pos,%lPs);
				%vel = Item::getVelocity(%player);
				%sta = Player::getItemState(%player,$WeaponSlot);
				%prp = Property::getPieceOwn(%obj).propID;
				if(%data.className == "Harvest") {
					%oPs = GameBase::getPosition(%obj);
					%pos = GameBase::getPosition(%player);
					%rltSkll = $Aeon::relativeSkill[%data];
					if($Aeon::ClientInfo[%id,skll,%rltSkll] > 0) {
						%oNm = $Aeon::SeedType[%data,%obj.type].description;
						if(%oNm == "")
							%oNm = $Aeon::SeedDefDesc[%data];
					}
					else {
						%oNm = $Aeon::SeedDefDesc[%data];
					}
					%oDs = Vector::getDistance(%pos,%oPs);
					if(%oDs < 10) {
						if(%obj.isRipe == true) {
							bottomPrint(%clientId,"<jc><f1>Construction Operations:<f2> selected "@%oNm,5);
							$CnGrab[%player] = %obj;
							%obj.cnGrabber = %player;
							%obj.cnGrabDst = %oDs;
							%clientId.tempGot = true;
							CnTool::isHolding(%player);
							GameBase::setPosition(%obj,Vector::add(%oPs,"0 0 0.2"));

							//$CnGrab[%player] = %obj;
							//%oPs = GameBase::getPosition(%obj);
							//%pos = GameBase::getPosition(%player);
							//%oDs = Vector::getDistance(%pos,%oPs);
							//%obj.cnGrabber = %player;
							//%obj.moveOnly = true;
							//%obj.cnGrabDst = %oDs;
						}
						else {
							if(%data == "Vege1")
								%ripeWord = "ripe";
							else
								%ripeWord = "ready";
							bottomPrint(%clientId,"<jc><f1>"@%oNm@" isn't "@%ripeWord@" yet.",5,"C_BuySell.wav");
							Player::trigger(%player,$WeaponSlot,false);
						}
					}
					else
						Player::trigger(%player,$WeaponSlot,false);
				}
				else if(%obj.isCoconut) {
					%oNm = "A Coconut!";
					bottomPrint(%clientId,"<jc><f1>Construction Operations:<f2> selected "@%oNm,5);
					%obj = Coconut::shapeSwap(%obj);
					$CnGrab[%player] = %obj;
					%oPs = GameBase::getPosition(%obj);
					%pos = GameBase::getPosition(%player);
					%oDs = Vector::getDistance(%pos,%oPs);
					%obj.cnGrabber = %player;
					%obj.cnGrabDst = %oDs;
					%clientId.tempGot = true;
					CnTool::isHolding(%player);
				}
				else if(%prp > 0 && AeonStr::trim(%prp) != "") {
					%act = String::getSubStr($CnModName[%mod],0,4);
					if(Property::hasPermission(%clientId,%prp,%act) || Aeon::getClosestOwnedProp(%ID,%pos) == %prp) {
						if(%typ == "InteriorShape" || %typ == "StaticShape" || %typ == "Item") {
							bottomPrint(%clientId,"<jc><f1>Construction Operations:<f2> selected "@%oNm,5);
							$CnGrab[%player] = %obj;
							%oPs = GameBase::getPosition(%obj);
							%oRt = GameBase::getRotation(%obj);
							%pos = GameBase::getPosition(%player);
							%rot = Player::getLookRot(%player);
							%oDs = Vector::getDistance(%pos,%lPs);
							%pVec = Vector::getFromRot(%rot,%oDs);
							%gPs = Vector::add(%pos,%pVec);
							%gVc = Vector::sub(%lPs,%oPs);
							
							%obj.cnGrabber = %player;
							%obj.cnGrabDst = %oDs;
							%obj.cdGrabRot = %rot;
							%obj.offVec = %gVc;
							%obj.lastPos = %oPs;
							%obj.lastRot = %oRt;
							%obj.lastGrabPos = %lPs;
							CnTool::isHolding(%player);
						}
						else
							Player::trigger(%player,$WeaponSlot,false);
					}
					else
						Player::trigger(%player,$WeaponSlot,false);
				}
				else if(%typ == "Item" || %typ == "Player") {
					if(((%prop = Aeon::inProperty(GameBase::getPosition(%obj))) && Property::getOwner(%prop) == Aeon::getAeonID(%clientId)) || %clientId.isSuperAdmin){
						%oNm = GameBase::getMapName(%obj);
						if(%oNm == "" || %oNm == -1) {
							if(%typ == "Item")
								%oNm = "An Item";
							else if(%typ == "Player")
								%oNm = "A Player";
						}
						bottomPrint(%clientId,"<jc><f1>Construction Operations:<f2> selected "@%oNm,5);
						$CnGrab[%player] = %obj;
						%oPs = GameBase::getPosition(%obj);
						%pos = GameBase::getPosition(%player);
						%oDs = Vector::getDistance(%pos,%oPs);
						%obj.cnGrabber = %player;
						%obj.moveOnly = true;
						%obj.cnGrabDst = %oDs;
						%clientId.tempGot = true;
						CnTool::isHolding(%player);
					}
					else if((%prop = Aeon::inProperty(GameBase::getPosition(%obj))) && !%clientId.isSuperAdmin) {
						if(Property::getOwner(%prop) == Aeon::getAeonID(Player::getClient(%obj)))
							Player::trigger(%player,$WeaponSlot,false);
					}
					else
						Player::trigger(%player,$WeaponSlot,false);
				}
				else if(%typ == "InteriorShape") {
					if(%obj.isRock && !%obj.cnGrabber) {
						bottomPrint(%clientId,"<jc><f1>Construction Operations:<f2> selected a Rock",5);
						$CnGrab[%player] = %obj;
						%oPs = GameBase::getPosition(%obj);
						%pos = GameBase::getPosition(%player);
						%oDs = Vector::getDistance(%pos,%oPs);
						%obj.cnGrabber = %player;
						%obj.cnGrabDst = %oDs;
						%clientId.tempGot = true;
						CnTool::isHolding(%player);
					}
				}
			}
			else {
				Player::trigger(%player,$WeaponSlot,false);
				if(Aeon::getClosestOwnedProp(%id,%pos) == Property::getPieceOwn(%obj))
					bottomPrint2(%clientId,"<jc><f1>"@%oNm@" is locked in place.",5,"C_BuySell.wav");
			}
		}
		else
			Player::trigger(%player,$WeaponSlot,false);
	}
	else {
		%pos = GameBase::getPosition(%player);
		%set = newObject("set",SimSet);
		if(containerBoxFillSet(%set,$ItemObjectType,%pos,20,20,40,-20)) {
			for(%i = 0; %i < Group::objectCount(%set); %i++) {
				%data = GameBase::getDataName(%obj = Group::getObject(%set,%i));
				if(String::findSubStr(%data,"Flag") != -1) {
					%oNm = GameBase::getMapName(%obj);
					if(%oNm == "" || %oNm == -1)
						%oNm = "a Flag";
					bottomPrint(%clientId,"<jc><f1>Construction Operations:<f2> selected "@%oNm,5);
					$CnGrab[%player] = %obj;
					%oPs = GameBase::getPosition(%obj);
					%oDs = Vector::getDistance(%pos,%oPs);
					%obj.moveOnly = true;
					%obj.cnGrabDst = %oDs;
					break;
				}
			}
		}
		else
			Player::trigger(%player,$WeaponSlot,false);
		deleteObject(%set);
	}
	schedule("CnTool::isHolding("@%player@");",0.3);
}

function CnTool::isHolding(%player)
{
	%state = Player::getItemState(%player,$WeaponSlot);
	%clientId = Player::getClient(%player);
	%id = Aeon::getAeonID(%clientId);
	if(%state == "Fire" && Player::getMountedItem(%player,$WeaponSlot) == "CnTool")
		$CnHold[%player] = true;
	else {
		$CnHold[%player] = "";
		if($CnGrab[%player] != "") {
			%obj = $CnGrab[%player];
			%obj.alignPos = "";
			%obj.alignRot = "";
			%obj.moveOnly = "";
			%obj.cnGrabber = "";
			%obj.cnGrabDst = "";
			%obj.cdGrabRot = "";
			%obj.offVec = "";
			%obj.deleting = "";
			%obj.lastGrabPos = "";
			$lastPos[%obj] = GameBase::getPosition(%obj);
			$CnGrab[%player] = "";
			%clientId.lastPiece = %obj;
			%clientId.lastCMod = $Aeon::ClientInfo[%id,cMod];
			if(%obj.bindLight) {
				Lights::turnOff(%obj);
				schedule("Lights::turnOn("@%obj@");",1.0,%obj);
			}
			if(%clientId.tempGot) {
				%clientId.tempGot = "";
				if(%obj.isCoconut)
					schedule("Coconut::restCheck("@%obj@");",1);
				else if(GameBase::getDataName(%obj).className == "Harvest") {
					%vel = %obj.vel;
					%obj = Harvest::pick(%obj);
					Item::setVelocity(%obj,%vel);
				}
			}
			else {
				bottomPrint(Player::getClient(%player),"<jc><f1>Construction Operations:<f2> released selection",5);
				%prop = Property::getPieceOwn(%obj);
				if(%prop)
					Aeon::ExportProperty(%prop);
			}
		}
	}
}

function CnTool::cycleModes(%clientId,%dir)
{
	%id = Aeon::getAeonID(%clientId);
	if(%dir == "")
		%dir = 1;
	if(%dir < 0) {
		if($CnModName[$Aeon::ClientInfo[%id,cMod]--] == "")
			$Aeon::ClientInfo[%id,cMod] = 9;
	}
	else {
		if($CnModName[$Aeon::ClientInfo[%id,cMod]++] == "")
			$Aeon::ClientInfo[%id,cMod] = 1;
	}
	CnTool::dispMode(%clientId);
}

function CnTool::setMode(%clientId,%mode)
{
	if(!%mode || %mode == "" || %mode == -1)
		%mode = 1;
	%id = Aeon::getAeonID(%clientId);
	$Aeon::ClientInfo[%id,cMod] = %mode;
	CnTool::dispMode(%clientId);
}

function CnTool::dispMode(%clientId)
{
	%id = Aeon::getAeonID(%clientId);	
	%desc = $CnModName[$Aeon::ClientInfo[%id,cMod]];
	if(AeonStr::ends(%desc,"by")) {
		if(!%clientId.archAngle)
			%clientId.archAngle = 2;
		%desc = %desc@" "@180/%clientId.archAngle;
	}
	else if(AeonStr::ends(%desc,"on"))
		%desc = %desc@" "@CnTool::getConstrString(%clientId);
	bottomPrint(%clientId,"<jc><f1>Construction Mode:<f2> "@%desc,5);
}

function CnTool::getConstrString(%clientId)
{
	%str = "";
	if(%clientId.archConst == "")
		%clientId.archConst = "true true true";
	if(getWord(%clientId.archConst,0) != false)
		%str = %str@"X ";
	if(getWord(%clientId.archConst,1) != false)
		%str = %str@"Y ";
	if(getWord(%clientId.archConst,2) != false)
		%str = %str@"Z";
	if(%str == "")
		%str = "None";
	%str = AeonStr::trim(%str);
	return %str;
}

function DeployPack::onUse(%player,%item)
{
	if(Player::getMountedItem(%player,$BackpackSlot) != %item)
		Player::mountItem(%player,%item,$BackpackSlot);
	else
		Player::deployItem(%player,%item);
}

function DeployPack::onDeploy(%player,%item,%pos)
{
	if(DeployPack::deployShape(%player,%item))
		Player::decItemCount(%player,%item);
}

function DeployPack::onMount(%player,%item)
{
	%client = Player::getClient(%player);
	Bottomprint(%client,"<jc><f3>Got a Package");
	%pack = $DeployPack[%client];
	Bottomprint(%client,"<jc><f3>Got a "@$DeployItem[%pack,desc]@" Package");
}

function DeployPack::deployShape(%player,%item)
{
	%clientId = Player::getClient(%player);
	if(GameBase::getLOSInfo(%player,7)) {
		%obj = getObjectType($los::object);
		if(%obj == "SimTerrain" || %obj == "InteriorShape" || %obj == "StaticShape") {
			%pos = GameBase::getPosition(%player);
			%rot = GameBase::getRotation(%player);
			%prop = Aeon::inProperty($los::position);
			if(%prop != false) {
				%id = Aeon::getAeonID(%clientId);
				%owner = Property::getOwner(%prop);
				if(%owner == %id || Property::hasPermission(%clientId,%prop,"deploy") == true) {
					%pack = $DeployPack[%clientId];
					%item = $DeployItem[%pack,item];
					%type = $DeployItem[%pack,type];
					%rot = GameBase::getRotation(%player);
					%shape = "";
					%ext = "";
					if(%type == "StaticShape")
						%ext = "true";
					else
						%shape = %item;
					%DeployStruct = newObject("",%type,%item,%ext);
					addToSet("MissionCleanup",%DeployStruct);
					%posMain = Vector::add($los::position,"0 0 0");
					GameBase::setPosition(%DeployStruct,%posMain);
					GameBase::setRotation(%DeployStruct,"0 0 0");
					if(%obj == "InteriorShape" || %obj == "StaticShape")
						$DeployStrAtt[%DeployStruct] = $los::object;
					else
						$DeployStrAtt[%DeployStruct] = "Base";
					GameBase::setMapName(%DeployStruct,$DeployItem[%pack,desc]);
					GameBase::setTeam(%DeployStruct,$Aeon::PropertyTeam);
					Property::owns(%prop,%DeployStruct,%shape);
					playSound(SoundPickupBackpack,$los::position);
					return true;
				}
				else
					bottomPrint2(%clientId,"<jc><f3>You don't have permission to deploy on this property.",1,"C_BuySell.wav");
			}
			else
				bottomPrint2(%clientId,"<jc><f3>You can only deploy on owned property.",1,"C_BuySell.wav");
		}
		else
			bottomPrint2(%clientId,"<jc><f3>You can only deploy on terrain or other objects.",1,"C_BuySell.wav");
	}
	else
		bottomPrint2(%clientId,"<jc><f3>Deploy position out of range.",1,"C_BuySell.wav");
	return false;
}