function Terminal::onCollision(%this,%object,%manual)
{
	%type = getObjectType(%object);
	%clientId = Player::getClient(%object);
	if(%type == "Player" && %clientId.isReading != true && %this.busy != true && %manual) {
		if(%object.Terminal == "") {
			if(Property::hasPermission(%clientId,%this.prop,"term")) {
				%pos1 = GameBase::getPosition(%this);
				%pos2 = GameBase::getPosition(%object);
				%dist = Vector::getDistance(%pos1,%pos2);
				%maxDist = $Terminal::useDist[GameBase::getDataName(%this)];
				if(%maxDist <= 0 || %maxDist == "")
					%maxDist = 3;
				if(%dist < %maxDist) {
					if(%this.userCount <= 0) {
						%this.userCount = 0;
						GameBase::setSequenceDirection(%this,1,1);
						GameBase::playSequence(%this,1,"activate");
					}
					%this.userCount++;
					%object.Terminal = %this;
					Terminal::shopping(%this,%object);
				}
				else {
					bottomPrint(%clientId,"<jc><f1>You must stand closer to use the <f2>"@GameBase::getDataName(%this).description@"<f1>.",2);
				}
			}
		}
		else if(%object.Terminal == %this) {
			%this.userCount--;
			%object.Terminal = "";
		}
	}
	else if(%type == "Item") {
		if(Property::hasPermission(Player::getClient(%object.tosser),%this.prop,"term")) {
			%data = GameBase::getDataName(%this);
			%item = GameBase::getDataName(%object);
			//if($Terminal::tossType[%data] == true)
			if($Terminal::tossType[%data] == true && ($Aeon::canSell[%item] != false || %data == "Term_CheckOut"))
				Eval(%data@"::onItemCatch("@%this@",\""@%object@"\");");
		}
	}
}

function Terminal::shopping(%this,%player)
{
	%clientId = Player::getClient(%player);
	%pos1 = GameBase::getPosition(%this);
	%pos2 = GameBase::getPosition(%player);
	%dist = Vector::getDistance(%pos1,%pos2);
	%maxDist = $Terminal::useDist[%data];
	if(%maxDist <= 0 || %maxDist == "")
		%maxDist = 3;
	if(%player.Terminal == %this && %dist < %maxDist) {
		%data = GameBase::getDataName(%this);
		if($Terminal::menuType[%data] == true) {
			if(%clientId.termMenu != true)
				Eval(%data@"::initMenu("@%clientId@",\"\","@%this@");");
			Eval(%data@"::showStats("@%clientId@","@%this@");");
		}
		else if($Terminal::shopType[%data] == true) {
			Terminal::buildList(%clientId,%this);
			Client::setGuiMode(%clientId,4);
		}
		%player.Terminal = %this;
		schedule("Terminal::shopping("@%this@","@%player@");",0.5,%this);
		return;
	}
	%clientId.giveTarget = "";
	remoteScoresOff(%clientId);
	if(Client::getGuiMode(%clientId) != 1)
		Client::setGuiMode(%clientId,1);
	Client::clearItemShopping(%clientId);
	if(%this.userCount <= 0) {
		%this.userCount = 0;
		GameBase::pauseSequence(%this,1);
		GameBase::setSequenceDirection(%this,1,0);
		GameBase::playSequence(%this,1);
	}
}

function Terminal::buildList(%clientId,%terminal)
{
	%max = getNumItems();
	%data = GameBase::getDataName(%terminal);
	%num = Terminal::getMarketNum(%terminal);
	for(%i = 0; %i < %max; %i++) {
		%item = getItemData(%i);
		if($TerminalList[%data,%num,%item] == true) {
			Client::setItemShopping(%clientId,%item);
			Client::setItemBuying(%clientId,%item);
		}
	}
	Client::setInventoryText(%clientId,"<jc><f1>Cash: "@String::cashComma($Aeon::ClientInfo[Aeon::getAeonID(%clientId),cash]));
}

function Terminal::getMarketNum(%this)
{
	%num = 1;
	for(%i = 1; $Aeon::Central["Market","Market_"@%i] != ""; %i++) {
		if($Aeon::Central["Market","Market_"@%i] == %this)
			return %i;
	}
	return %num;
}

function Terminal::countInv(%data,%num)
{
	%max = getNumItems();
	%count = 0;
	for(%i = 0; %i < %max; %i++) {
		%item = getItemData(%i);
		if($TerminalList[%data,%num,%item] == true)
			%count++;
	}
	return %count;
}

function Terminal::purchase(%clientId,%item)
{
	%id = Aeon::getAeonID(%clientId);
	%player = Client::getOwnedObject(%clientId);
	%cost = floor($TerminalCost[%item]);
	if(Client::isItemShoppingOn(%clientId,%item) && $Aeon::ClientInfo[%id,cash] >= %cost) {
		%count = Player::getItemCount(%clientId,%item);
		%cash = $Aeon::ClientInfo[%id,cash] -= floor(%cost);
		Player::setItemCount(%clientId,%item,%count+1);
		%ammoItem =  %item.imageType.ammoType; 
		if(%ammoItem != "" && %ammoItem != false)
			Player::setItemCount(%clientId,%ammoitem,Player::getItemCount(%clientId,%ammoitem)+1);
		Client::setInventoryText(%clientId,"<jc><f1>Cash: "@String::cashComma(%cash));
		return true;
 	}
	return false;
}

function Terminal::sell(%clientId,%item)
{
	%id = Aeon::getAeonID(%clientId);
	%player = Client::getOwnedObject(%clientId);
	%cost = $TerminalCost[%item]*0.2;
	if(Player::getItemCount(%clientId,%item) > 0 && Client::getGuiMode(%clientId) == 4 && $Aeon::InteractFunc[%player.Terminal] == "Term_Sales" && $Aeon::canSell[%item] != false) {
		%cash = $Aeon::ClientInfo[%id,cash] += floor(%cost);
		%count = Player::getItemCount(%clientId,%item);
		Player::setItemCount(%clientId,%item,%count-1);
		Client::setInventoryText(%clientId,"<jc><f1>Cash: "@String::cashComma(%cash));
		return floor(%cost);	
 	}
	return false;
}

