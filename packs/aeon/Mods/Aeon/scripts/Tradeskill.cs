}

function Combine::getAmalg(%this)
{
	%lastGot = false;
	%invStr = Combine::strInv(%this);
	%max = getNumItems();
	for(%i = 0; %i < %max; %i++) {
		%data = getItemData(%i);
		%ingStr = $Combine::ingredStr[%data];
		if(%ingStr != "" && String::ICompare(%invStr,%ingStr) == 0) {
			%lastGot = %data;
			break;
		}
	}
	return %lastGot;
}

function Combine::strCompare(%str1,%str2)
{
	%len1 = AeonStr::getWordCount(%str1);
	%len2 = AeonStr::getWordCount(%str2);
	%len = %len1;
	if(%len2 > %len1)
		%len = %len2;
	%count = %len;
	for(%i = 0; %i < %len; %i++) {
		%word1 = getWord(%str1,%i);
		%word2 = getWord(%str2,%i);
		if(%word1 != %word2)
			break;
		%count--;
	}
}

function Combine::strInv(%term)
{
	%str = "";
	%max = getNumItems();
	for(%i = 0; %i < %max; %i++) {
		%data = getItemData(%i);
		if($Aeon::Combine[%term,inv,%data] > 0)
			%str = Combine::countIngred(%term,%str,%data);
	}
	return %str;
}

function Combine::strIngred(%item)
{
	%str = "";
	%max = getNumItems();
	for(%i = 0; %i < %max; %i++) {
		%data = getItemData(%i);
		%count = Combine::compareElement(%item,%data);
		if(%count > 0)
			%str = Combine::countElm(%data,%str,%count);
	}
	return %str;
}

function Combine::countIngred(%term,%str,%data)
{
	%count = $Aeon::Combine[%term,inv,%data];
	if(%count < 0)
		%count = 0;
	for(%i = 0; %i < %count; %i++)
		%str = %str@%data@" ";
	return %str;
}

function Combine::countElm(%item,%str,%count)
{
	for(%i = 0; %i < %count; %i++)
		%str = %str@%item@" ";
	return %str;
}

function Combine::compareElement(%item,%data)
{
	%count = 0;
	for(%i = 0; $Aeon::Elements[%item,%i] != ""; %i++) {
		if($Aeon::Elements[%item,%i] == %data)
			%count++;
	}
	if(%count > 0)
		return %count;
	return false;
}

function Combine::canMake(%clientId,%amalg)
{
	if($Aeon::makeSkll[%amalg,0] == "none")
		return true;
	%id = Aeon::getAeonId(%clientId);
	for(%i = 0; $Aeon::makeSkll[%amalg,%i] != ""; %i++) {
		%reqr = $Aeon::makeSkll[%amalg,%i];
		%skll = $Aeon::ClientInfo[%id,skll,getWord(%reqr,0)];
		if(%skll < getWord(%reqr,1))
			return false;
	}
	return true;
}

