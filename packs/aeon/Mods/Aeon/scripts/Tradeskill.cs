function Aeon::countItems()
{
	%max = getNumItems();
}

function Combine::invCount(%this)
{
	%count = 0;
	%max = getNumItems();
	for(%i = 0; %i < %max; %i++) {
		%data = getItemData(%i);
		if($Aeon::Combine[%this,inv,%data] > 0)
			%count++;
			//%count+=$Aeon::Combine[%this,inv,%data];
	}
	return %count;
}

function Combine::invReset(%this)
{
	%max = getNumItems();
	for(%i = 0; %i < %max; %i++)
		$Aeon::Combine[%this,inv,getItemData(%i)] = "";
}

function Term_Combine::onAdd(%this)
{
	GameBase::playSequence(%this,2,"deploy");
	Combine::invReset(%this);
	$Aeon::InteractFunc[%this] = "Term_Combine";
	Terminal::onAdd(%this);
}

function Term_Combine::onRemove(%this)
{
	Combine::invReset(%this);
}

function Term_Combine::onInteract(%this,%player)
{
	Terminal::onCollision(%this,%player,true);
}

function Term_Combine::onItemCatch(%this,%object)
{
	%player = %object.tosser;
	%clientId = Player::getClient(%player);
	%data = GameBase::getDataName(%object);
	%all = Combine::invCount(%this);
	if(%all < $Combine::maxInput || $Aeon::Combine[%this,inv,%data] > 0) {
		deleteObject(%object);
		if($Aeon::Combine[%this,inv,%data] < 1)
			$Aeon::Combine[%this,inv,%data] = 0;
		%count = $Aeon::Combine[%this,inv,%data]++;
		%desc = Item::getDescription(%data,%count);
		bottomPrint(%clientId,"<jc><f1>You added <f2>1 "@%data.description@"<f1>, Total: <f2>"@%count@" "@%desc@"<f1>.",3);
	}
	else
		bottomPrint(%clientId,"<jc><f1>Combination Terminal Full!",3);
}

function Term_Combine::initMenu(%clientId,%null,%this)
{
	%clientId.termMenu = true;
	%id = Aeon::getAeonID(%clientId);
	Client::buildMenu(%clientId,"Combination: ","Combine",true);
	%num = 0;
	%elements = 0;
	%max = getNumItems();
	for(%i = 0; %i < %max && %num < $Combine::maxInput; %i++) {
		%data = getItemData(%i);
		%count = $Aeon::Combine[%this,inv,%data];
		if(%count > 0) {
			%name = %data.description@" x "@%count;
			%elements += %count;
			Client::addMenuItem(%clientId,%num++@%name,%this@" item "@%i);
		}
	}
	if(%elements < 1)
		Client::addMenuItem(%clientId,%num++@"No Items...",%this@" none");
	else
		Client::addMenuItem(%clientId,%num++@"Combine",%this@" combine");
	Client::addMenuItem(%clientId,%num++@"Cancel",%this@" exit");
	return;
}

function processMenuCombine(%clientId,%opt)
{
	%id = Aeon::getAeonId(%clientId);
	%term = getWord(%opt,0);
	%portT = Client::getOwnedObject(%clientId).Terminal; // PORT (2026-10-12): must be the terminal the caller is standing at
	if(%portT == "" || !(%portT == %term)) return;
	%op1 = getWord(%opt,1);
	%op2 = getWord(%opt,2);
	%clientId.termMenu = "";
	%clientId.lastTermMenu = getSimTime();
	if(%op1 == "exit") {
		remoteScoresOff(%clientId);
		return;
	}
	else if(%op1 == "none") {
		bottomPrint(%clientId,"<jc><f3>You must add Items to be Combined!",3);
		Term_Combine::initMenu(%clientId,true,%term);
		return;
	}
	else if(%op1 == "item") {
		%data = getItemData(%op2);
		%count = $Aeon::Combine[%term,inv,%data];
		if(%count > 0) {
			if(Item::giveItem(%clientId,%data,1)) {
				$Aeon::Combine[%term,inv,%data]--;
				%desc = Item::getDescription(%data,%count);
				bottomPrint(%clientId,"<jc><f1>You removed <f2>1<f1> of <f2>"@%count@" "@%desc@"<f1>.",3);
				Term_Combine::initMenu(%clientId,true,%term);
				return;
			}
		}
	}
	else if(%op1 == "combine") {
		%amalg = Combine::getAmalg(%term);
		if(%amalg != false) {
			if(Combine::canMake(%clientId,%amalg)) {
				for(%i = 0; $Aeon::Elements[%amalg,%i] != ""; %i++)
					$Aeon::Combine[%term,inv,$Aeon::Elements[%amalg,%i]]--;
				bottomPrint(%clientId,"<jc><f1>You Amalgamized <f2>1<f1> <f2>"@%amalg.description@"<f1>!",3);
				//Term_Combine::initMenu(%clientId,true,%term);
				remoteScoresOff(%clientId);
				Term_Combine::Work(%term,%amalg);
				return;
			}
			else
				bottomPrint(%clientId,"<jc><f3>You lack the Skill to Combine these Items!",3);
		}
		else
			bottomPrint(%clientId,"<jc><f3>Could not Combine these Items!",3);
	}
}

function Term_Combine::Work(%this,%item)
{
	%this.busy = true;
	GameBase::pauseSequence(%this,2);
	GameBase::setSequenceDirection(%this,2,0);
	GameBase::playSequence(%this,2);
	schedule("Term_Combine::endWork("@%this@","@%item@");",1.0,%this);
}

function Term_Combine::endWork(%this,%item)
{
	GameBase::pauseSequence(%this,2);
	GameBase::setSequenceDirection(%this,2,1);
	GameBase::playSequence(%this,2);
	$Aeon::Combine[%this,inv,%item]++;
	schedule(%this@".busy = \"\";",1.0,%this);
}

