function FetchCharge::damageTarget(%target, %timeSlice, %damPerSec, %enDrainPerSec, %pos, %vec, %mom, %shooter)
{
	%clientId = Player::getClient(%target);
	%player = %target;
	if(Client::getTeam(%clientId) != Client::getTeam(%shooter))
		return;
	
	echo(Client::getName(%shooter) @ " is fetching " @ Client::getName(%clientId));
	GameBase::playSound(%player,ForceFieldOpen,0);
	Client::sendMessage(%clientId,1,Client::getName(%shooter) @ " has fetched you!");
	%hasflag = Player::getMountedItem(%player, 2);
	if(%hasflag!=-1 && %hasflag!="DeadWeight")
	{
		Player::dropItem(%player, %hasflag);
      		Client::sendMessage(%clientId,1,"While teleporting, you dropped the flag...");
	}
	Player::setDamageFlash(%player, 0.4);
	if(%player.cloakPack == 0 && %player.cloakBoost == 0 && %player.cloaked == 0 && %player.cloakdevice == 0 && %player.cloakplane == 0 && %player.cloakGun == 0)
	 	GameBase::startFadein(%player);
	%spawnMarker = GameBase::getPosition(%shooter);
	%xPos = getWord(%spawnMarker, 0) + floor(getRandom() * 15) - 7.5;
	%yPos = getword(%spawnMarker, 1) + floor(getRandom() * 15) - 7.5;
	%zPos = getWord(%spawnMarker, 2) + 5;
	%rPos = GameBase::getRotation(%shooter);
	%SpawnPos = %xPos @ "  " @ %yPos @ "  " @ %zPos;
	GameBase::setPosition(%player, %SpawnPos);
}

