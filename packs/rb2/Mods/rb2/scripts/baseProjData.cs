function Stormbots_startCloak(%this)
{
	echo("Cloaking item " @ %this);
	%this.cloakGun = 1;
	if($cloakTime[%this] <= 0)
	{
		$cloakTime[%this] = 120;
	        GameBase::startFadeOut(%this);
	        GameBase::playSound(%this,ForceFieldOpen,0);
		checkItemCloaked(%this);
	}
	else
		$cloakTime[%this] = 9120;
}

function checkItemCloaked(%this)
{
	if($cloakTime[%this] > 0)
	{
		$cloakTime[%this] -= 5;
		if (getObjectType(%this) == "Player" && Player::isDead(%this))
		{
			$cloakTime[%this] = 0;
			schedule("checkItemCloaked(" @ %this @ ");",0.5,%this);
		}
		else
			schedule("checkItemCloaked(" @ %this @ ");",5,%this);
	}
	else
	{
		if(%this.cloakPack == 0 && %this.cloakBoost == 0 && %this.cloaked == 0 && %this.cloakdevice == 0 && %this.cloakplane == 0 && %this.cloakGun == 1)
		{
			GameBase::startFadeIn(%this);
			GameBase::playSound(%this,ForceFieldClose,0);
		}
		%this.cloakGun = 0; 
	}
}

