// Default power animation behavior for all static shapes

function StaticShape::onCollision(%this, %object) {
	// if the player is an engineer specialist and the object is friendly, repair the object
	if (Player::getArmor(%object) == engineerarmor && GameBase::getTeam(%object) == GameBase::getTeam(%this)) {
		EffectRepairs(%object, %this);
		return;
	}

}

function StaticShape::onPower(%this,%power,%generator)
{
	if (%power) 
		GameBase::playSequence(%this,0,"power");
	else 
		GameBase::stopSequence(%this,0);
}

function StaticShape::onEnabled(%this)
{
	if (GameBase::isPowered(%this)) 
		GameBase::playSequence(%this,0,"power");
}

function StaticShape::onDisabled(%this)
{
	GameBase::stopSequence(%this,0);

	// Notify RepairBot of disabledness
	dRepairBot::initiateRepairs(%this, false);

}

function StaticShape::onUndeployed(%this)
{
	// clear all effects
	$burnTime[%this] = 0;
	$acidBurnTime[%this] = 0;

	GameBase::stopSequence(%this,0);
	StaticShape::objectiveDestroyed(%this);

	// Notify RepairBot of destruction
	dRepairBot::initiateRepairs(%this, true);

	// Notify ForceShield of destruction
	ForceShield::targetObjectDestroyed(%this);
}


function StaticShape::onDestroyed(%this)
{
	// clear all effects
	$burnTime[%this] = 0;
	$acidBurnTime[%this] = 0;

	GameBase::stopSequence(%this,0);
	StaticShape::objectiveDestroyed(%this);
	calcRadiusDamage(%this, $DebrisDamageType, 2.5, 0.05, 25, 13, 2, 0.40, 
		0.1, 250, 100); 

	// Notify RepairBot of destruction
	dRepairBot::initiateRepairs(%this, true);

	// Notify ForceShield of destruction
	ForceShield::targetObjectDestroyed(%this);
}

function StaticShape::onDamage(%this,%type,%value,%pos,%vec,%mom,%object)
{

	// Activate ForceShield, if any
	%value = ForceShield::Activate(%this, %value, %pos, %vec, %object);

	// Activate Shield Generator shield, if in range
	%value = ShieldGenerator::Activate(%this, %value, %pos, %vec, %object);

	// If the damage was not fully absorbed
	if (%value > 0) {

		// Get the current damage level
		%damageLevel = GameBase::getDamageLevel(%this);

		// Calculate the updated damage level
		%dValue = %damageLevel + %value;

		// Set the last object to damage this object
		%this.lastDamageObject = %object;

		// Set the last team to damage this object
		%this.lastDamageTeam = GameBase::getTeam(%object);

		// If the shooter and this object are on the same team
		// And if this is not a remote bomb
		if(GameBase::getTeam(%this) == GameBase::getTeam(%object) && %type != $RemoteBombDamageType) {

			// Get the name of this object
			%name = GameBase::getDataName(%this);

			// If it's a generator or a station
			if(%name.className == Generator || %name.className == Station) { 

				// Calculate any damage reduction for being on the same team
				%TDS = $Server::TeamDamageScale;
				%dValue = %damageLevel + %value * %TDS;
	
				// Get the amount of damage that would "disable" this object
				%disable = GameBase::getDisabledDamage(%this);

				// If the server is not in tournament, and the damage wouldn't disable the object
				if(!$Server::TourneyMode && %dValue > %disable - 0.05) {

					// If the object is too close to being disabled, quit
					if(%damageLevel > %disable - 0.05)
						return;
            				else
						%dValue = %disable - 0.05;
				}
			}
		}
	
		// If Fire damage, we start the burn effect
		if (%type == $FireDamageType) {

			startObjectBurn(%this);
		}
	
		// If Acid damage, we start the acid effect
		if (%type == $AcidDamageType) {

			startObjectAcidBurn(%this);
		}

		// Apply the damage
		GameBase::setDamageLevel(%this,%dValue);

	}
}

function StaticShape::shieldDamage(%this,%type,%value,%pos,%vec,%mom,%object)
{

	// Get this object's damage level
	%damageLevel = GameBase::getDamageLevel(%this);

	// Get the object that last damaged this object
	%this.lastDamageObject = %object;

	// Get the team that last damaged this object
	%this.lastDamageTeam = GameBase::getTeam(%object);

	// For Blind Damage, we do nothing
	if (%type == $BlindDamageType) {

		%value = 0;
		return;
	}

	// If this object HAS any shield strength
	if (%this.shieldStrength) {

		// Get it's current energy level
		%energy = GameBase::getEnergy(%this);

		// Get it's current shield strength
		%strength = %this.shieldStrength;

		// If it's taking shrapnel damage, decrease its resistance 50%
		if (%type == $ShrapnelDamageType)
			%strength *= 0.5;
		else {
			// If it's taking mortar damage, decrease its resistance 25%
			if (%type == $MortarDamageType)
				%strength *= 0.25;
			else {
				// If it's taking blaster damage, double its resistance
				if (%type == $BlasterDamageType)
					%strength *= 2.0;
				else {
					// If it's taking acid damage, the shield is ineffective
					if (%type == $AcidDamageType)
						%strength = 0;
				}
			}
		}

		// Calculate how much damage the shield will absorb
		%absorb = %energy * %strength;

		// If the damage doesn't make it through the shield
		if (%value < %absorb) {

			// Reduce this object's energy
			GameBase::setEnergy(%this,%energy - (%value / %strength));

			// Calculate a position around the object where the projectile hit
			%centerPos = getBoxCenter(%this);
			%sphereVec = findPointOnSphere(getBoxCenter(%object),%centerPos,%vec,%this);
			%centerPosX = getWord(%centerPos,0);
			%centerPosY = getWord(%centerPos,1);
			%centerPosZ = getWord(%centerPos,2);

			%pointX = getWord(%pos,0);
			%pointY = getWord(%pos,1);
			%pointZ = getWord(%pos,2);

			%newVecX = %centerPosX - %pointX;
			%newVecY = %centerPosY - %pointY;
			%newVecZ = %centerPosZ - %pointZ;
			%norm = Vector::normalize(%newVecX @ " " @ %newVecY @ " " @ %newVecZ);
			%zOffset = 0;

			// Tweak for the pulse sensor
			if(GameBase::getDataName(%this) == PulseSensor)
				%zOffset = (%pointZ-%centerPosZ) * 0.5;

			// Display the shield effect in the proper position
			GameBase::activateShield(%this,%sphereVec,%zOffset);

			// If EMP damage was done
			if(%type == $EMPDamageType) { 

				// Drain the object's energy by 50%
				GameBase::setEnergy(%this,(%this.shieldStrength * 0.5)); 
				playSound(SoundEMPDrain,GameBase::getPosition(%this)); 
			} 
		}

		// But if the damage went through the shield
		else {
			// Take away 75% of the object's energy
			GameBase::setEnergy(%this, GameBase::getEnergy(%this) * 0.75);

			// Damage the object
			StaticShape::onDamage(%this,%type,%value - %absorb,%pos,%vec,%mom,%object);
		}
	}

	// But if this object has no shield
	else {
		// Damage the object normally
		StaticShape::onDamage(%this,%type,%value,%pos,%vec,%mom,%object);
	}
}

