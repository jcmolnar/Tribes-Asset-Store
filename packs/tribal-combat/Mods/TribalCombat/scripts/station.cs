	{
		%player = Station::getTarget(%this);

		//*****************
		//Reset Global Vars
		//*****************
		if(%player != -1)
		 {
		  %client = Player::getClient(%player);
		  $Combat::timeOut[%client] = 0;
	      $assaultShield[%client] = false;
          %player.shieldStrength = 0;
		  $Combat::playerProne[%client] = false;

