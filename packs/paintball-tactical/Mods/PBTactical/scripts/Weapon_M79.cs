function M79Image::onFire(%player,%slot)
{
	if($canFireUS[%player] == "") { $canFireUS[%player] = true; }
	
	if($canFireUS[%player])
	{
		%armor = Player::getArmor(%player);
		if(%armor == "larmor" || %armor == "lfemale") { %cMax = 250; }	
		doFire(%player, 0, %cMax);
		$canFireUS[%player] = false;
	}
}
function doFire(%player,%chargeRate,%cMax)
{	
	if(%chargeRate < %cMax)
	{
		if(Player::getItemCount(%player,TLPack) == 1)
			%chargeRate += 1;	 
		else
			%chargeRate += 2;
		bottomprint(player::getClient(%player), "<f0> Pump Gage: <f1>"@%chargeRate@"<f0> m", 0.3);
	}
	else if(%chargeRate >= %cMax)
	{
		bottomprint(player::getClient(%player), "<f0> Pump Gage: <f1>"@%cMax@"<f0> m :MAX PSI:", 0.8);
		%chargeRate = %cMax;
	}
	
	if(Player::getItemState(%player,$weaponslot) != "Fire")
	{
		%trans = GameBase::getMuzzleTransform(%player);
		%vel = Item::getVelocity(%player);
		for(%i=0; %i < 1; %i++) 
		{
			%trans = GameBase::getMuzzleTransform(%player);
			%vel = Item::getVelocity(%player);
			if(%chargeRate < 25)
				Projectile::spawnProjectile("M79Shell25m",%trans,%player,%vel);
			else if(%chargeRate < 50)
				Projectile::spawnProjectile("M79Shell50m",%trans,%player,%vel);
			else if(%chargeRate < 75)
				Projectile::spawnProjectile("M79Shell75m",%trans,%player,%vel);
			else if(%chargeRate < 100)
				Projectile::spawnProjectile("M79Shell100m",%trans,%player,%vel);
			else if(%chargeRate < 125)
				Projectile::spawnProjectile("M79Shell125m",%trans,%player,%vel);
			else if(%chargeRate < 150)
				Projectile::spawnProjectile("M79Shell150m",%trans,%player,%vel);
			else if(%chargeRate < 175)
				Projectile::spawnProjectile("M79Shell175m",%trans,%player,%vel);
			else if(%chargeRate < 200)
				Projectile::spawnProjectile("M79Shell200m",%trans,%player,%vel);
			else if(%chargeRate < 225)
				Projectile::spawnProjectile("M79Shell225m",%trans,%player,%vel);
			else if(%chargeRate < 250)
				Projectile::spawnProjectile("M79Shell250m",%trans,%player,%vel);
			else
				Projectile::spawnProjectile("M79Shell250m2",%trans,%player,%vel);
				Player::decItemCount(%player,M79Ammo);
		}
		$canFireUS[%player] = true;	
	}
	else
		schedule("doFire("@%player@","@%chargeRate@","@%cMax@");",0.04);
}

