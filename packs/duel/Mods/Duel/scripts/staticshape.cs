function remoteSP(%client)
{
	%cpos = gamebase::getposition(%client);
	%x = getword(%cpos, 0)+floor((getRandom()*2.5)*100)/100 ;
	%y = getword(%cpos, 1)+floor((getRandom()*2.5)*100)/100 ;
	%z = getword(%cpos, 2)+floor((getRandom()*2.5)*100)/100 ;

	%class="StaticShape";
	%type = "sparkle";
	%spawn = newObject(%type,"StaticShape",%type,true);
	addToSet("MissionCleanup", %spawn);

	echo("spawn: "@%spawn@"    Player: "@%cpos@"    New: "@%x@" "@%y@" "@%z);

	gamebase::setposition(%spawn, %x@" "@%y@" "@%z);
}





