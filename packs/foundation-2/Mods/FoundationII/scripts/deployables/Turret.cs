function TurretPack::onUse(%player,%item)
{
	if (Player::getMountedItem(%player,$BackpackSlot) != %item) {
		Player::mountItem(%player,%item,$BackpackSlot);
	}
	else {
		Player::deployItem(%player,%item);
	}
}

function TurretPack::onDeploy(%player,%item,%pos)
{
	if (Item::universalDeploy(%player,%item,4,"LAND",$TurretBoxMaxLength,$TurretBoxMaxWidth,$TurretBoxMaxHeight,$TurretBoxMinLength,$TurretBoxMinWidth,$TurretBoxMinHeight,$MaxNumTurretsInBox,false,DeployableTurret,"Turret",true))
		Player::decItemCount(%player,%item);
}

